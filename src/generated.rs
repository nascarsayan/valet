//! Files valet generates. Each starts with a header that names the command
//! regenerating it, is written atomically, and is then locked against hand
//! edits: mode 0444. Rewriting or removing one unlocks it first.

use anyhow::{Context, Result};
use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::Path;

/// This tool's name (`valet`), whatever it was called through (git hooks
/// call it as `pre-commit`): headers, commands and completions use it.
pub fn name() -> &'static str {
    env!("CARGO_BIN_NAME")
}

/// The source checkout's folder name (`<what> in the <repo> repo`).
fn repo() -> String {
    Path::new(crate::cmd::upgrade::REPO)
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_default()
}

/// `` `<name> <args>` ``, a regenerate command for [`header`].
pub fn cmd(args: &str) -> String {
    format!("`{} {args}`", name())
}

/// `<what> in the <repo> repo`, a source for [`header`] texts.
pub fn source(what: &str) -> String {
    format!("{what} in the {} repo", repo())
}

/// The header line for a file with `comment` as its line-comment marker.
pub fn header(comment: &str, regenerate: &str) -> String {
    format!(
        "{comment} Generated by {}; do not edit (the file is locked). Regenerate: {regenerate}\n",
        name()
    )
}

/// Write `body` (header included by the caller) to `path` unless it already
/// holds exactly that, then lock it. True when the file changed.
pub fn write(path: &Path, body: &str) -> Result<bool> {
    write_mode(path, body, 0o444)
}

/// [`write`] with the locked mode (0o555 for a script).
pub fn write_mode(path: &Path, body: &str, mode: u32) -> Result<bool> {
    if fs::read_to_string(path).is_ok_and(|t| t == body) {
        lock_mode(path, mode);
        return Ok(false);
    }
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir)?;
    }
    unlock(path);
    let tmp = path.with_extension("valet-tmp");
    fs::write(&tmp, body).with_context(|| format!("write {}", tmp.display()))?;
    fs::rename(&tmp, path).with_context(|| format!("write {}", path.display()))?;
    lock_mode(path, mode);
    Ok(true)
}

/// Remove a generated file (no error when it is already gone).
pub fn remove(path: &Path) -> Result<()> {
    if fs::symlink_metadata(path).is_err() {
        return Ok(());
    }
    unlock(path);
    fs::remove_file(path).with_context(|| format!("remove {}", path.display()))
}

/// Lock a file valet just produced by other means (for example `zcompile`).
pub fn lock(path: &Path) {
    lock_mode(path, 0o444);
}

fn lock_mode(path: &Path, mode: u32) {
    let Ok(md) = fs::symlink_metadata(path) else {
        return;
    };
    if !md.is_file() {
        return;
    }
    if md.permissions().mode() & 0o777 != mode {
        unlock(path);
        let _ = fs::set_permissions(path, fs::Permissions::from_mode(mode));
    }
}

/// Make a locked file writable again.
pub fn unlock(path: &Path) {
    let Ok(md) = fs::symlink_metadata(path) else {
        return;
    };
    if !md.is_file() {
        return;
    }
    let _ = fs::set_permissions(path, fs::Permissions::from_mode(0o644));
}

/// `README.md` for a folder of generated files: what each entry is and the
/// command that regenerates it. `entries` are `(name, what, args)`; the
/// command is `<binary name> <args>`.
pub fn readme(dir: &Path, title: &str, entries: &[(&str, &str, &str)]) -> Result<bool> {
    let (name, repo) = (name(), repo());
    let mut s = format!(
        "<!-- Generated by {name}; do not edit (the file is locked). -->\n# {title}\n\n\
         Everything here is generated by `{name}` and locked (mode 0444). Do not edit; change the source in the {repo} repo and rerun the command.\n\n\
         | Entry | What | Regenerate |\n|---|---|---|\n"
    );
    for (name, what, args) in entries {
        s.push_str(&format!("| `{name}` | {what} | {} |\n", cmd(args)));
    }
    write(&dir.join("README.md"), &s)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn write_locks_and_rewrites() {
        let d = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join(".tmp")
            .join(format!("valet-generated-{}", std::process::id()));
        fs::create_dir_all(&d).unwrap();
        let f = d.join("x.sh");
        let body = format!("{}echo hi\n", header("#", "`valet x`"));
        assert!(write(&f, &body).unwrap());
        assert_eq!(
            fs::metadata(&f).unwrap().permissions().mode() & 0o222,
            0,
            "read-only"
        );
        assert!(!write(&f, &body).unwrap(), "unchanged");
        assert!(write(&f, &format!("{body}echo 2\n")).unwrap());
        remove(&f).unwrap();
        assert!(!f.exists());
        let _ = fs::remove_dir_all(&d);
    }
}
