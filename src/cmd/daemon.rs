    fn fails() -> Result<Cmd> {
        Ok(Cmd::new("false"))
    }
    fn sleeps() -> Result<Cmd> {
        Ok(Cmd::new("sleep").arg("60"))
    }
    fn missing() -> Result<Cmd> {
        bail!("not configured")
    }
    static TEST_PARTS: &[Part] = &[
        Part {
            name: "bad",
            what: "",
            cmd: fails,
        },
        Part {
            name: "good",
            what: "",
            cmd: sleeps,
        },
        Part {
            name: "broken",
            what: "",
            cmd: missing,
        },
    ];

    fn wait_exit(s: &mut Slot) {
        let (c, _) = s.child.as_mut().expect("running");
        for _ in 0..200 {
            if let Ok(Some(st)) = c.try_wait() {
                // try_wait reaped it; keep the status for the next tick.
                assert!(!st.success());
                return;
            }
            std::thread::sleep(Duration::from_millis(10));
        }
        panic!("child did not exit");
    }

    #[test]
    fn crashing_part_restarts_with_backoff_and_others_keep_running() {
        let mut sup = Supervisor::new(TEST_PARTS, None);
        let all = |_: &str| true;
        let t0 = Instant::now();
        sup.tick(&all, t0);
        assert!(sup.slots.iter().take(2).all(|s| s.child.is_some()));
        // A part whose command cannot be built is retried later, like a crash.
        assert!(sup.slots[2].child.is_none());
        assert_eq!(sup.slots[2].next_start, Some(t0 + Duration::from_secs(1)));
        let good = sup.slots[1].child.as_ref().unwrap().0.id();

        wait_exit(&mut sup.slots[0]);
        sup.tick(&all, t0);
        assert!(sup.slots[0].child.is_none());
        assert_eq!(sup.slots[0].next_start, Some(t0 + Duration::from_secs(1)));
        // Not before its delay.
        sup.tick(&all, t0 + Duration::from_millis(500));
        assert!(sup.slots[0].child.is_none());
        let t1 = t0 + Duration::from_secs(1);
        sup.tick(&all, t1);
        assert!(sup.slots[0].child.is_some());
        wait_exit(&mut sup.slots[0]);
        sup.tick(&all, t1);
        assert_eq!(sup.slots[0].next_start, Some(t1 + Duration::from_secs(2)));
        assert_eq!(sup.slots[2].next_start, Some(t1 + Duration::from_secs(2)));

        // The healthy part was never touched.
        let (c, _) = sup.slots[1].child.as_mut().unwrap();
        assert_eq!(c.id(), good);
        assert!(c.try_wait().unwrap().is_none());

        // Turned off: stopped, and its backoff forgotten.
        let only_good = |n: &str| n == "good";
        sup.tick(&only_good, t1);
        assert!(sup.slots[0].next_start.is_none());
        assert!(sup.slots[1].child.is_some());
        let off = |_: &str| false;
        sup.tick(&off, t1);
        assert!(sup.slots.iter().all(|s| s.child.is_none()));
    }

    #[test]
    fn daily_slot_is_0330_local_and_catches_up() {
        let day = 86_400;
        let midnight = 20_000 * day; // a UTC midnight
        // UTC: from 01:00 -> today 03:30 (+ spread).
        let d = next_due(midnight + 3600, 0);
        assert!((midnight + DAILY_AT..midnight + DAILY_AT + SPREAD).contains(&d));
        // Just after today's slot -> tomorrow's.
        let d = next_due(midnight + DAILY_AT, 0);
        assert!((midnight + day + DAILY_AT..midnight + day + DAILY_AT + SPREAD).contains(&d));
        // UTC-8: 03:30 local is 11:30 UTC.
        let d = next_due(midnight, -8 * 3600);
        let slot = midnight + DAILY_AT + 8 * 3600;
        assert!((slot..slot + SPREAD).contains(&d));
        // Down for three days: due long ago, so it runs at once.
        assert!(next_due(midnight - 3 * day, 0) < midnight);
        // The delay differs from day to day.
        let delays: std::collections::BTreeSet<i64> = (0..30)
            .map(|i| next_due(midnight + i * day, 0) - (midnight + i * day + DAILY_AT))
            .collect();
        assert!(delays.len() > 20, "{delays:?}");
    }

