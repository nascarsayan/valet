/// How often the repos part looks at the folders.
const REPOS_POLL: Duration = Duration::from_secs(5);

/// Each folder with its mtime and inode: adding, removing or renaming an
/// entry changes its folder's mtime.
type Signature = Vec<(PathBuf, Option<(i64, i64, u64)>)>;

fn signature(dirs: Vec<PathBuf>) -> Signature {
    use std::os::unix::fs::MetadataExt;
    dirs.into_iter()
        .map(|d| {
            let m = fs::metadata(&d)
                .ok()
                .map(|m| (m.mtime(), m.mtime_nsec(), m.ino()));
            (d, m)
        })
        .collect()
}

/// Reconcile at start and whenever a watched folder changes (the folders are
/// listed again each pass, so new repos and worktrees are watched at once).
fn repos_part() -> Result<()> {
    let mut last: Option<Signature> = None;
    loop {
        let now = signature(crate::repos::watch_dirs()?);
        if last.as_ref() != Some(&now) {
            for l in crate::repos::reconcile(false)? {
                crate::info!("{l}");
            }
            // What reconcile itself changed is not a change to act on.
            last = Some(signature(crate::repos::watch_dirs()?));
        }
        std::thread::sleep(REPOS_POLL);
    }
}

/// Local time of day the daily run is due, and the spread after it.
const DAILY_AT: i64 = 3 * 3600 + 30 * 60;
const SPREAD: i64 = 20 * 60;

fn unix_now() -> i64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0)
}

/// The first daily slot ([`DAILY_AT`] local; OFF: UTC offset in seconds)
/// after LAST, plus a per-day delay under [`SPREAD`]. A slot missed while
/// the host was down is due at once.
fn next_due(last: i64, off: i64) -> i64 {
    let local = last + off;
    let mut slot = local.div_euclid(86_400) * 86_400 + DAILY_AT;
    if slot <= local {
        slot += 86_400;
    }
    let slot = slot - off;
    slot + (mix(slot.unsigned_abs()) % SPREAD as u64) as i64
}

/// splitmix64's finalizer: spreads slots (all multiples of 30 min) evenly.
fn mix(mut x: u64) -> u64 {
    x = (x ^ (x >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
    x = (x ^ (x >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
    x ^ (x >> 31)
}

/// `date +%z` (`+0530`, `-0800`) in seconds.
fn parse_offset(z: &str) -> Result<i64> {
    let z = z.trim();
    let (sign, digits) = match z.as_bytes().first() {
        Some(b'+') => (1, &z[1..]),
        Some(b'-') => (-1, &z[1..]),
        _ => bail!("bad UTC offset {z:?}"),
    };
    if digits.len() != 4 || !digits.bytes().all(|b| b.is_ascii_digit()) {
        bail!("bad UTC offset {z:?}");
    }
    let (h, m): (i64, i64) = (digits[..2].parse()?, digits[2..].parse()?);
    Ok(sign * (h * 3600 + m * 60))
}

fn utc_offset() -> Result<i64> {
    parse_offset(&crate::proc::output(
        "date",
        &["+%z"],
        Duration::from_secs(5),
    )?)
}

fn stamp_file() -> Result<PathBuf> {
    Ok(host_dir()?.join("job-last-run"))
}

/// The last daily run (unix time); a missing stamp is written as now.
fn last_run(create: bool) -> Result<Option<i64>> {
    let p = stamp_file()?;
    match fs::read_to_string(&p) {
        Ok(t) => t
            .trim()
            .parse()
            .map(Some)
            .with_context(|| format!("{} is not a unix time", p.display())),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound && create => {
            write_stamp(unix_now())?;
            Ok(Some(unix_now()))
        }
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(e).with_context(|| format!("read {}", p.display())),
    }
}

fn write_stamp(t: i64) -> Result<()> {
    fs::create_dir_all(host_dir()?)?;
    fs::write(stamp_file()?, format!("{t}\n"))?;
    Ok(())
}

/// When the daily run is next due on this host (unix time), if it ran before.
pub fn next_job_run() -> Option<i64> {
    Some(next_due(last_run(false).ok()??, utc_offset().ok()?))
}

/// Start the daily run when due (the stamp first: a restart never starts it twice).
fn job_part() -> Result<()> {
    let mut told = None;
    loop {
        let last = last_run(true)?.expect("created");
        let due = next_due(last, utc_offset()?);
        let now = unix_now();
        if now >= due {
            write_stamp(now)?;
            match crate::cmd::job::start_daily() {
                Ok(()) => crate::info!("started the daily run (`valet job status run`)"),
                Err(e) => crate::warn!("daily run not started: {e:#}"),
            }
            continue;
        }
        if told != Some(due) {
            crate::info!("next daily run {}", crate::log::iso_from_unix(due));
            told = Some(due);
        }
        std::thread::sleep(Duration::from_secs((due - now).clamp(1, 60) as u64));
    }
}

