//! `valet daemon`: every long-running part in one systemd user unit,
//! `valet-daemon.service`, which runs `valet daemon run`: a supervisor that
//! starts each part that is on as its own child process (own process group),
//! prefixes every line a part prints with `[<part>] ` in the journal, and
//! restarts a part that exits, with backoff ([`Backoff`]). One part failing
//! leaves the others running. Parts are processes, not threads: `valet cc`
//! exits its process to restart.
//!
//! Which parts are on is per host (the home dir and Userland are shared
//! between VMs): `<State>/daemon/<host>/parts.json`, `{"cc": true, ...}`,
//! written by the commands that use a part (`valet cc`, `repos watch`,
//! `job enable|disable`) or by `valet daemon on|off`. A file that does not parse, or names an unknown part,
//! stops every part (fail closed) until it is fixed.

use crate::cmd::systemd::{install_user_unit, user_systemctl, user_unit_dir};
use crate::proc::Cmd;
use anyhow::{Context, Result, bail};
use std::collections::BTreeMap;
use std::fs;
use std::io::{BufRead, BufReader, Read};
use std::path::{Path, PathBuf};
use std::process::Child;
use std::time::{Duration, Instant, SystemTime, UNIX_EPOCH};

/// One supervised part: NAME starts as the program `cmd` returns.
pub struct Part {
    pub name: &'static str,
    pub what: &'static str,
    pub cmd: fn() -> Result<Cmd>,
}

pub const PARTS: &[Part] = &[
    Part {
        name: "cc",
        what: "valet cc: Claude sessions <-> the Slack DM",
        cmd: cc_cmd,
    },
    Part {
        name: "tabs",
        what: "herdr tab labels follow each tab's host or Claude session (custom names stay)",
        cmd: tabs_cmd,
    },
    Part {
        name: "repos",
        what: "reconcile repos when repo or worktree folders change",
        cmd: repos_cmd,
    },
    Part {
        name: "job",
        what: "start the daily `valet job run` (~03:30 local)",
        cmd: job_cmd,
    },
];

/// How often the supervisor checks its parts and parts.json.
const TICK: Duration = Duration::from_secs(1);
/// A stopped part gets this long after SIGTERM before SIGKILL.
const STOP_GRACE: Duration = Duration::from_secs(10);
const SYSTEMCTL: Duration = Duration::from_secs(20);

#[derive(clap::Args)]
pub struct Args {
    #[command(subcommand)]
    cmd: Sub,
}

#[derive(clap::Subcommand)]
enum Sub {
    /// Write the unit, enable and (re)start it; `--off` stops, disables and
    /// removes it.
    Install {
        #[arg(long)]
        off: bool,
        #[arg(short = 'n', long)]
        dry_run: bool,
    },
    /// The unit's state and each part's.
    Status,
    /// Turn a part on for this host (it starts within seconds).
    On { part: String },
    /// Turn a part off for this host (the daemon stops it).
    Off { part: String },
    /// Restart one part, or the whole daemon (no PART).
    Restart { part: Option<String> },
    /// Recent log lines, of one part (prefix stripped) or all.
    Logs {
        part: Option<String>,
        #[arg(short = 'n', long, default_value_t = 50)]
        lines: usize,
    },
    /// Run the supervisor in the foreground (what the unit runs).
    #[command(hide = true)]
    Run,
    /// Run an in-process part (repos, job) in the foreground.
    #[command(hide = true)]
    Part { name: String },
}

pub fn run(a: Args) -> Result<()> {
    match a.cmd {
        Sub::Install { off: true, .. } => uninstall(),
        Sub::Install {
            off: false,
            dry_run,
        } => install(dry_run).map(drop),
        Sub::Status => status(),
        Sub::On { part } => ensure(&part),
        Sub::Off { part } => {
            set_part(&part, false)?;
            println!("{part}: off");
            Ok(())
        }
        Sub::Restart { part } => restart(part.as_deref()),
        Sub::Logs { part, lines } => {
            for l in log_lines(part.as_deref(), lines)? {
                println!("{l}");
            }
            Ok(())
        }
        Sub::Run => supervise(),
        Sub::Part { name } => match name.as_str() {
            "repos" => repos_part(),
            "job" => job_part(),
            "tabs" => crate::cmd::cc::herdr::tabs_part(),
            _ => bail!("no in-process part {name:?} (repos, job, tabs)"),
        },
    }
}

// ---------- unit ----------

fn unit() -> String {
    format!("{}-daemon.service", crate::generated::name())
}

/// ExecStart goes through zsh, which reads `~/.zshenv`: this host's
/// `$USERLAND`, PATH and app env, so the shared unit names no host's path.
fn unit_text(zsh: &Path) -> String {
    let name = crate::generated::name();
    let parts: Vec<&str> = PARTS.iter().map(|p| p.name).collect();
    format!(
        "# Generated by {} ({}).\n\
         [Unit]\nDescription={name} daemon: {}\n\n\
         [Service]\nExecStart={} -c 'exec \"$${{USERLAND}}/Commands/$${{USERLAND_ARCH}}/{name}\" daemon run'\n\
         Restart=on-failure\nRestartSec=10\n\n\
         [Install]\nWantedBy=default.target\n",
        crate::generated::cmd("daemon install"),
        crate::generated::source("src/cmd/daemon.rs"),
        parts.join(", "),
        zsh.display(),
    )
}

/// Write the unit, enable and start it; restarted when its text changed.
/// Returns whether it changed.
fn install(dry: bool) -> Result<bool> {
    let text = unit_text(&crate::cmd::job::zsh());
    if dry {
        let path = user_unit_dir()?.join(unit());
        if fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
            println!("update {}", path.display());
        }
        return Ok(false);
    }
    let changed = install_user_unit(&unit(), &text, true)?;
    user_systemctl(&["enable", "--now", &unit()])?;
    Ok(changed)
}

fn uninstall() -> Result<()> {
    let p = user_unit_dir()?.join(unit());
    if p.exists() {
        let _ = user_systemctl(&["disable", "--now", &unit()]);
        fs::remove_file(&p).with_context(|| format!("remove {}", p.display()))?;
        println!("removed {}", p.display());
        user_systemctl(&["daemon-reload"])?;
    }
    Ok(())
}

/// Turn PART on and make sure the daemon is installed and running.
pub fn ensure(part: &str) -> Result<()> {
    check_part(part)?;
    install(false)?;
    if set_part(part, true)? {
        println!("{part}: on");
    }
    Ok(())
}

/// After `valet upgrade`: the unit rewritten and restarted on the new binary.
pub fn after_upgrade() {
    let r = install(false).and_then(|changed| {
        if !changed {
            user_systemctl(&["restart", &unit()])?;
        }
        Ok(())
    });
    if let Err(e) = r {
        crate::warn!("{} after upgrade failed: {e:#}", unit());
    }
}

fn restart(part: Option<&str>) -> Result<()> {
    let Some(part) = part else {
        if !install(false)? {
            user_systemctl(&["restart", &unit()])?;
        }
        return Ok(());
    };
    restart_part(part)
}

/// Stop PART's processes; the daemon starts it again (it is on).
pub fn restart_part(part: &str) -> Result<()> {
    check_part(part)?;
    match running_pid(part) {
        Some(pid) => {
            signal_group(pid, "TERM")?;
            println!("{part}: restarting");
        }
        None => {
            println!("{part}: not running; the daemon starts it when on (`valet daemon status`)")
        }
    }
    Ok(())
}

fn status() -> Result<()> {
    // Both exit non-zero for an inactive or disabled unit; the word is on stdout.
    let state = |a: &str| {
        Cmd::new("systemctl")
            .args(["--user", a, &unit()])
            .timeout(SYSTEMCTL)
            .output()
            .ok()
            .map(|o| o.stdout.trim().to_owned())
            .filter(|s| !s.is_empty())
            .unwrap_or_else(|| "not installed".into())
    };
    println!(
        "{}: {} ({})",
        unit(),
        state("is-active"),
        state("is-enabled")
    );
    for p in PARTS {
        println!("  {:10} {:22} {}", p.name, part_state(p.name)?, p.what);
    }
    Ok(())
}

/// Whether PART is on for this host.
pub fn part_on(part: &str) -> Result<bool> {
    Ok(is_on(&load_parts()?.unwrap_or_default(), part))
}

/// Whether the running daemon runs PART now.
pub fn part_running(part: &str) -> bool {
    running_pid(part).is_some()
}

/// `on, running (pid N)`, `on, not running`, or `off`.
pub fn part_state(part: &str) -> Result<String> {
    let on = is_on(&load_parts()?.unwrap_or_default(), part);
    Ok(match (on, running_pid(part)) {
        (_, Some(pid)) => format!("{}, running (pid {pid})", if on { "on" } else { "off" }),
        (true, None) => "on, not running".into(),
        (false, None) => "off".into(),
    })
}

/// The journal's last N lines; with PART only its lines, prefix stripped.
pub fn log_lines(part: Option<&str>, n: usize) -> Result<Vec<String>> {
    // A part's lines are a share of the journal: read more, then filter.
    let read = if part.is_some() { n.max(1) * 50 } else { n };
    let out = Cmd::new("journalctl")
        .args(["--user", "-u", &unit(), "--no-pager", "-o", "cat", "-n"])
        .arg(read.to_string())
        .timeout(SYSTEMCTL)
        .checked()?;
    Ok(filter_part(&out, part, n))
}

fn filter_part(text: &str, part: Option<&str>, n: usize) -> Vec<String> {
    let v: Vec<String> = match part {
        None => text.lines().map(str::to_owned).collect(),
        Some(p) => {
            let pre = format!("[{p}] ");
            text.lines()
                .filter_map(|l| l.strip_prefix(&pre).map(str::to_owned))
                .collect()
        }
    };
    v[v.len().saturating_sub(n)..].to_vec()
}

// ---------- parts.json ----------

fn host_dir() -> Result<PathBuf> {
    Ok(crate::cmd::apps::self_dir("State")?
        .join("daemon")
        .join(crate::cmd::apps::host()))
}

fn parts_file() -> Result<PathBuf> {
    Ok(host_dir()?.join("parts.json"))
}

fn check_part(name: &str) -> Result<()> {
    if PARTS.iter().any(|p| p.name == name) {
        return Ok(());
    }
    let names: Vec<&str> = PARTS.iter().map(|p| p.name).collect();
    bail!("no part {name:?}; parts: {}", names.join(", "))
}

/// Part -> on. Unknown parts fail.
fn parse_parts(text: &str) -> Result<BTreeMap<String, bool>> {
    let m: BTreeMap<String, bool> =
        serde_json::from_str(text).context("parts.json: expected {\"<part>\": true|false}")?;
    for k in m.keys() {
        check_part(k).context("parts.json")?;
    }
    Ok(m)
}

/// None when the file is missing (every part off).
fn load_parts() -> Result<Option<BTreeMap<String, bool>>> {
    let p = parts_file()?;
    match fs::read_to_string(&p) {
        Ok(t) => parse_parts(&t)
            .with_context(|| p.display().to_string())
            .map(Some),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(e).with_context(|| format!("read {}", p.display())),
    }
}

fn is_on(parts: &BTreeMap<String, bool>, name: &str) -> bool {
    parts.get(name).copied().unwrap_or(false)
}

fn save_parts(parts: &BTreeMap<String, bool>) -> Result<()> {
    let p = parts_file()?;
    fs::create_dir_all(host_dir()?)?;
    let tmp = p.with_extension(format!("json.tmp.{}", std::process::id()));
    fs::write(&tmp, serde_json::to_string_pretty(parts)? + "\n")?;
    fs::rename(&tmp, &p)?;
    Ok(())
}

/// Turn PART on or off for this host. Returns whether that changed it.
pub fn set_part(part: &str, on: bool) -> Result<bool> {
    check_part(part)?;
    let mut parts = load_parts()?.unwrap_or_default();
    if is_on(&parts, part) == on && parts.contains_key(part) {
        return Ok(false);
    }
    parts.insert(part.to_owned(), on);
    save_parts(&parts)?;
    Ok(true)
}

// ---------- supervisor ----------

/// Restart delay after a part exits: 1 s doubling to 5 min while it keeps
/// failing fast; a run of [`HEALTHY`] or longer starts over at 1 s.
#[derive(Default, Debug)]
struct Backoff {
    fails: u32,
}

const BACKOFF_MIN: Duration = Duration::from_secs(1);
const BACKOFF_MAX: Duration = Duration::from_secs(300);
const HEALTHY: Duration = Duration::from_secs(60);

impl Backoff {
    /// The delay before the next start, after a run that lasted RAN.
    fn next(&mut self, ran: Duration) -> Duration {
        if ran >= HEALTHY {
            self.fails = 0;
        }
        let d = BACKOFF_MIN
            .saturating_mul(1 << self.fails.min(10))
            .min(BACKOFF_MAX);
        self.fails += 1;
        d
    }
}

struct Slot {
    part: &'static Part,
    child: Option<(Child, Instant)>,
    backoff: Backoff,
    next_start: Option<Instant>,
}

struct Supervisor {
    slots: Vec<Slot>,
    /// Where `<part>.pid` files go (None: none, in tests).
    pid_dir: Option<PathBuf>,
}

fn say(part: &str, level: &str, msg: &str) {
    eprintln!("[{part}] {} {level} {msg}", crate::log::now_iso());
}

impl Supervisor {
    fn new(parts: &'static [Part], pid_dir: Option<PathBuf>) -> Self {
        let slots = parts
            .iter()
            .map(|part| Slot {
                part,
                child: None,
                backoff: Backoff::default(),
                next_start: None,
            })
            .collect();
        Supervisor { slots, pid_dir }
    }

    fn pid_file(&self, part: &str) -> Option<PathBuf> {
        self.pid_dir.as_ref().map(|d| d.join(format!("{part}.pid")))
    }

    /// One pass at time NOW: reap exited parts (schedule their restart),
    /// stop parts turned off, start parts that are on and due.
    fn tick(&mut self, on: &dyn Fn(&str) -> bool, now: Instant) {
        for i in 0..self.slots.len() {
            let name = self.slots[i].part.name;
            let want = on(name);
            let pid_file = self.pid_file(name);
            let s = &mut self.slots[i];
            if let Some((child, since)) = &mut s.child {
                match child.try_wait() {
                    Ok(Some(st)) => {
                        let ran = now.saturating_duration_since(*since);
                        let d = s.backoff.next(ran);
                        say(
                            "daemon",
                            "WARN",
                            &format!(
                                "{name} exited ({st}) after {}s; restart in {}s",
                                ran.as_secs(),
                                d.as_secs()
                            ),
                        );
                        s.child = None;
                        s.next_start = Some(now + d);
                        if let Some(p) = &pid_file {
                            let _ = fs::remove_file(p);
                        }
                    }
                    Ok(None) if !want => {
                        stop(child);
                        say("daemon", "INFO", &format!("{name} stopped (turned off)"));
                        s.child = None;
                        if let Some(p) = &pid_file {
                            let _ = fs::remove_file(p);
                        }
                    }
                    Ok(None) => {}
                    Err(e) => say("daemon", "WARN", &format!("{name}: wait failed: {e}")),
                }
            }
            if s.child.is_some() {
                continue;
            }
            if !want {
                s.next_start = None;
                s.backoff = Backoff::default();
                continue;
            }
            if s.next_start.is_some_and(|t| now < t) {
                continue;
            }
            match start(s.part) {
                Ok(child) => {
                    say(
                        "daemon",
                        "INFO",
                        &format!("{name} started (pid {})", child.id()),
                    );
                    if let Some(p) = &pid_file {
                        let _ = fs::write(p, child.id().to_string());
                    }
                    s.child = Some((child, now));
                    s.next_start = None;
                }
                Err(e) => {
                    let d = s.backoff.next(Duration::ZERO);
                    say(
                        "daemon",
                        "ERROR",
                        &format!("{name} did not start: {e:#}; retry in {}s", d.as_secs()),
                    );
                    s.next_start = Some(now + d);
                }
            }
        }
    }

    fn stop_all(&mut self) {
        for s in &mut self.slots {
            if let Some((mut c, _)) = s.child.take() {
                stop(&mut c);
            }
        }
    }
}

/// Start PART with its output forwarded, line by line, as `[<part>] line`.
fn start(part: &'static Part) -> Result<Child> {
    let mut child = (part.cmd)()?.spawn_piped()?;
    forward(part.name, child.stdout.take());
    forward(part.name, child.stderr.take());
    Ok(child)
}

fn forward(name: &'static str, r: Option<impl Read + Send + 'static>) {
    let Some(r) = r else { return };
    std::thread::spawn(move || {
        let mut r = BufReader::new(r);
        let mut buf = Vec::new();
        while r.read_until(b'\n', &mut buf).is_ok_and(|n| n > 0) {
            let line = String::from_utf8_lossy(&buf);
            eprintln!("[{name}] {}", line.trim_end_matches(['\n', '\r']));
            buf.clear();
        }
    });
}

/// SIGTERM to the part's process group, SIGKILL after [`STOP_GRACE`].
fn stop(child: &mut Child) {
    let _ = signal_group(child.id(), "TERM");
    let t0 = Instant::now();
    while t0.elapsed() < STOP_GRACE {
        if child.try_wait().is_ok_and(|s| s.is_some()) {
            return;
        }
        std::thread::sleep(Duration::from_millis(100));
    }
    let _ = signal_group(child.id(), "KILL");
    let _ = child.wait();
}

fn signal_group(pid: u32, sig: &str) -> Result<()> {
    crate::proc::output(
        "kill",
        &[&format!("-{sig}"), "--", &format!("-{pid}")],
        Duration::from_secs(5),
    )
    .map(drop)
}

fn supervise() -> Result<()> {
    let dir = host_dir()?;
    fs::create_dir_all(&dir)?;
    let mut sup = Supervisor::new(PARTS, Some(dir));
    say("daemon", "INFO", "up");
    loop {
        let parts = match load_parts() {
            Ok(p) => p.unwrap_or_default(),
            Err(e) => {
                sup.stop_all();
                return Err(e.context("every part stopped"));
            }
        };
        sup.tick(&|n| is_on(&parts, n), Instant::now());
        std::thread::sleep(TICK);
    }
}

/// The pid of PART's process when the running daemon started it.
fn running_pid(part: &str) -> Option<u32> {
    let pid: u32 = fs::read_to_string(host_dir().ok()?.join(format!("{part}.pid")))
        .ok()?
        .trim()
        .parse()
        .ok()?;
    let main: u32 = crate::proc::output(
        "systemctl",
        &["--user", "show", "-p", "MainPID", "--value", &unit()],
        SYSTEMCTL,
    )
    .ok()?
    .parse()
    .ok()?;
    let stat = fs::read_to_string(format!("/proc/{pid}/stat")).ok()?;
    (main != 0 && parent_of(&stat) == Some(main)).then_some(pid)
}

/// The parent pid in a `/proc/<pid>/stat` line (after the `(comm)` field).
fn parent_of(stat: &str) -> Option<u32> {
    stat.rsplit_once(')')?
        .1
        .split_whitespace()
        .nth(1)?
        .parse()
        .ok()
}

