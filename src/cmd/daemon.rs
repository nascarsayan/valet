        let got: Vec<u64> = (0..11).map(|_| b.next(quick).as_secs()).collect();
        assert_eq!(got, [1, 2, 4, 8, 16, 32, 64, 128, 256, 300, 300]);
        assert_eq!(b.next(HEALTHY).as_secs(), 1);
        assert_eq!(b.next(quick).as_secs(), 2);
