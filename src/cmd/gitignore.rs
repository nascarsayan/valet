//! The global gitignore: `[git] ignore` in config.toml, written by
//! `valet hooks install` to `<Userland>/Applications/Git/Settings/ignore` and
//! set as git's `core.excludesFile`.

use crate::proc::Cmd;
use anyhow::{Result, bail};
use std::path::PathBuf;

#[derive(serde::Deserialize, Default)]
#[serde(deny_unknown_fields)]
struct Config {
    #[serde(default)]
    ignore: Vec<String>,
}

fn parse(text: &str) -> Result<Config> {
    let c: Config = crate::config::section_of(text, "git")?;
    for p in &c.ignore {
        if p.trim().is_empty() || p.contains('\n') || p.trim_start().starts_with('#') {
            bail!("config.toml [git] ignore: bad pattern {p:?}");
        }
    }
    Ok(c)
}

/// Check `[git]` of config TEXT.
pub fn validate(text: &str) -> Result<()> {
    parse(text).map(drop)
}

/// `<Userland>/Applications/Git/Settings/ignore`.
pub fn path() -> Result<PathBuf> {
    Ok(crate::cmd::apps::root()?.join("Applications/Git/Settings/ignore"))
}

/// [`path`] as `core.excludesFile` names it: `~/...` through the home dir's
/// link, since every host reads git's global config.
pub fn value() -> Result<String> {
    Ok(crate::cmd::apps::portable_tilde(&path()?))
}

fn render(c: &Config) -> String {
    let mut s = crate::generated::header(
        "#",
        &format!(
            "{} (source: {})",
            crate::generated::cmd("hooks install"),
            crate::generated::source("config.toml [git]")
        ),
    );
    for p in &c.ignore {
        s.push_str(p);
        s.push('\n');
    }
    s
}

/// git's current global `core.excludesFile`.
pub fn current() -> Option<String> {
    Cmd::new("git")
        .args(["config", "--global", "--get", "core.excludesFile"])
        .checked()
        .ok()
        .map(|s| s.trim().to_owned())
        .filter(|s| !s.is_empty())
}

/// Write the file and point `core.excludesFile` at it. Returns the previous
/// value when it changed it (for `uninstall`).
pub fn install(dry: bool) -> Result<Option<String>> {
    let c = parse(crate::config::text()?)?;
    let p = path()?;
    let body = render(&c);
    let say = |m: String| println!("{}{m}", if dry { "would: " } else { "" });
    if std::fs::read_to_string(&p).ok().as_deref() != Some(&body) {
        say(format!("write {}", p.display()));
        if !dry {
            crate::generated::write(&p, &body)?;
        }
    }
    let before = current();
    let target = value()?;
    if before.as_deref() == Some(&target) {
        return Ok(None);
    }
    // An older spelling of this same file is not a setting to restore.
    let before = before.filter(|b| {
        let b = match b.strip_prefix("~/") {
            Some(rest) => crate::cmd::home().map(|h| h.join(rest)).unwrap_or_default(),
            None => PathBuf::from(b),
        };
        crate::cmd::apps::canonical(&b) != p
    });
    say(format!(
        "git config --global core.excludesFile {target} (was {})",
        before.as_deref().unwrap_or("unset")
    ));
    if !dry {
        Cmd::new("git")
            .args(["config", "--global", "core.excludesFile", &target])
            .checked()?;
    }
    Ok(before)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_patterns_after_header() {
        let c = parse("[git]\nignore = [\".tmp/\", \"*.pyc\"]\n").unwrap();
        let s = render(&c);
        assert!(s.starts_with("# Generated by "));
        assert!(s.ends_with("\n.tmp/\n*.pyc\n"));
    }

    #[test]
    fn rejects_bad_patterns_and_keys() {
        assert!(parse("[git]\nignore = [\"\"]\n").is_err());
        assert!(parse("[git]\nignore = [\"a\\nb\"]\n").is_err());
        assert!(parse("[git]\nother = 1\n").is_err());
        assert!(parse("").unwrap().ignore.is_empty());
    }
}
